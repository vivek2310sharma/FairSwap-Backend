-- Use a stable UUID for each new key, independent of environment-specific legacy UUIDs.
create function pg_temp.mobile_catalogue_id(key text) returns uuid
language sql immutable strict set search_path = '' as $$
  select overlay(overlay(substr(digest, 1, 32) placing '8' from 13)
                 placing 'a' from 17)::uuid
  from (select encode(sha256(convert_to('fairswap/posting-v2/india-phones/' || key, 'UTF8')), 'hex') as digest) hashed
$$;

-- Ignore case, display-brand prefixes, and common formatting variations.
-- Keep network suffixes and generation numbers unless explicitly reconciled below.
create function pg_temp.mobile_catalogue_key(brand text, model text) returns text
language sql immutable strict set search_path = '' as $$
  select regexp_replace(replace(
    regexp_replace(lower(btrim(model) collate "C"), '^' || lower(brand collate "C") || ' +', ''),
    '+', 'plus'), '[[:space:]()-]+', '', 'g')
$$;

create temporary table mobile_catalogue_brand_plan on commit drop as
select seed.*, existing.id as existing_id,
       pg_temp.mobile_catalogue_id('brand/' || lower(seed.name collate "C")) as seed_id
from mobile_catalogue_brands seed
left join public.phone_brands existing on lower(btrim(existing.name) collate "C") = lower(seed.name collate "C");

-- Multiple live names for one canonical brand must fail before any inserts.
alter table mobile_catalogue_brand_plan add primary key (name);

do $$
begin
  if to_regprocedure('public.posting_v2_catalogue()') is null or exists (
    select 1 from mobile_catalogue_brand_plan where new_sort_order is null and existing_id is null
  ) then
    raise exception 'Posting V2 legacy catalogue is incomplete';
  end if;
  if exists (
    select 1 from mobile_catalogue_brand_plan plan
    join public.phone_brands occupied on occupied.id = plan.seed_id
    where plan.new_sort_order is not null and occupied.id is distinct from plan.existing_id
  ) then
    raise exception 'Mobile catalogue brand ID collision';
  end if;
end $$;

