create temporary table mobile_catalogue_model_plan on commit drop as
with excluded(brand, model) as (values
  -- Generic names overlap generation-specific Nokia rows already in the catalogue.
  ('Nokia', 'Nokia 105'),
  ('Nokia', 'Nokia 110 4G'),
  -- Bare names overlap existing 5G models. The source does not distinguish the network variant.
  ('Infinix', 'Infinix Note 40 Pro'),
  ('Tecno', 'Tecno Camon 30'),
  -- HMD's manual identifies the 2780 Flip as a Nokia model.
  ('HMD', 'HMD 2780 Flip')
), equivalent(brand, model, display) as (values
  -- Explicit equivalences. Never strip 4G/5G generically.
  ('Samsung', 'Galaxy A55', 'Galaxy A55 5G'),
  ('Samsung', 'Galaxy M35', 'Galaxy M35 5G'),
  ('Oppo', 'Oppo Reno11', 'Reno11 5G'),
  ('Oppo', 'Oppo Reno11 Pro', 'Reno11 Pro 5G'),
  ('Realme', 'Realme 12 Pro', '12 Pro 5G'),
  ('Realme', 'Realme 12 Pro+', '12 Pro+ 5G'),
  ('POCO', 'POCO X6', 'X6 5G'),
  ('POCO', 'POCO X6 Pro', 'X6 Pro 5G'),
  ('POCO', 'POCO M4', 'M4 5G'),
  ('Lava', 'Lava Agni 2', 'Agni 2 5G')
), names as (
  select source.brand, source.model,
         coalesce(equivalent.display,
                  regexp_replace(source.model, '^' || source.brand || ' +', '', 'i')) as display
  from mobile_catalogue_source source
  left join equivalent using (brand, model)
  where not exists (
    select 1 from excluded where excluded.brand = source.brand and excluded.model = source.model
  )
), candidates as (
  select brand, display,
         case when display = model then '{}'::text[] else array[model] end as aliases,
         pg_temp.mobile_catalogue_key(brand, display) as model_key,
         pg_temp.mobile_catalogue_key(brand, model) as source_key,
         (99 + row_number() over (partition by brand order by lower(display collate "C"), display))::integer as sort_order,
         false as other
  from names
  union all
  select name, 'Other model', '{}'::text[], 'othermodel', 'othermodel', 999, true
  from mobile_catalogue_brand_plan
  where new_sort_order is not null
)
select candidates.*, coalesce(brand_plan.existing_id, brand_plan.seed_id) as brand_id,
       pg_temp.mobile_catalogue_id('model/' || lower(brand collate "C") || '/' || model_key) as seed_id,
       existing.id as existing_id, existing.other as existing_other, existing.older_group as existing_older
from candidates
join mobile_catalogue_brand_plan brand_plan on brand_plan.name = candidates.brand
left join public.phone_models existing
  on existing.brand_id = coalesce(brand_plan.existing_id, brand_plan.seed_id)
 and (
   (candidates.other and existing.other)
   or exists (
     select 1 from unnest(array[existing.name] || existing.aliases) as labels(label)
     where pg_temp.mobile_catalogue_key(candidates.brand, labels.label) in (model_key, source_key)
   )
 );

-- Reject one-to-many and many-to-one identity matches, including alias collisions.
alter table mobile_catalogue_model_plan add primary key (brand_id, model_key);
alter table mobile_catalogue_model_plan add unique (existing_id);

do $$
begin
  if (select count(*) from mobile_catalogue_source) <> 1418
    or (select count(*) from mobile_catalogue_model_plan where not other) <> 1413 then
    raise exception 'Unexpected mobile catalogue source or intake count';
  end if;
  if exists (
    select 1 from mobile_catalogue_model_plan
    where existing_id is not null and (existing_other <> other or existing_older)
  ) then
    raise exception 'Mobile catalogue model collides with a fallback or older group';
  end if;
  if exists (
    select 1 from mobile_catalogue_model_plan plan
    join public.phone_models occupied on occupied.id = plan.seed_id
    where occupied.id is distinct from plan.existing_id
  ) then
    raise exception 'Mobile catalogue model ID collision';
  end if;
end $$;

insert into public.phone_models (id, brand_id, name, aliases, sort_order, enabled, older_group, other)
select seed_id, brand_id, display, aliases, sort_order, true, false, other
from mobile_catalogue_model_plan
where existing_id is null;

do $$
begin
  if exists (
    select 1 from mobile_catalogue_brand_plan plan
    left join public.phone_models fallback
      on fallback.brand_id = coalesce(plan.existing_id, plan.seed_id) and fallback.other
    group by plan.name
    having count(fallback.id) <> 1
  ) then
    raise exception 'Each mobile catalogue brand must retain exactly one Other model';
  end if;
end $$;

